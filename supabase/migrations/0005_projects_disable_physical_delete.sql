-- ============================================================================
-- projects: authenticated / anon の物理DELETE権限を剥奪
-- ============================================================================
-- 目的：
--   soft delete（deleted_at）を「削除済みである」ことの唯一の記録として
--   使うため、既存コードの書き損じや将来の実装ミスによって物理DELETEが
--   発行されてしまう経路自体を閉じる。
--
-- 【重要：適用タイミング】
--   本migrationは、必ず以下がすべて完了したあとに適用すること：
--     1. 0004（deleted_at列・インデックス追加）が本番へ適用済み
--     2. soft delete方式で現場削除を行う新アプリコードがVercelへ
--        デプロイ済み・動作確認済み
--   0004単独適用時点ではまだ物理DELETEを発行する旧アプリが稼働している
--   可能性があるため、その状態でこのREVOKEだけを先に適用すると、
--   旧アプリ経由の現場削除操作が権限エラーで失敗してしまう。
--   新アプリの動作確認が取れてから本migrationを適用することで、
--   デプロイのどの瞬間でも削除操作が破綻しないようにする。
--
-- service_role / postgres の DELETE権限には触れない（将来の管理者処理・
-- データ整理用に維持する）。既存RLSポリシー（projects_select_own /
-- _update_own / _delete_own）も変更しない
-- （projects_delete_own ポリシー自体は残すが、本migration適用後は
--   authenticated/anonがそもそもDELETE権限を持たないため実質到達不能で無害）。
-- ============================================================================

revoke delete on public.projects from authenticated, anon;
